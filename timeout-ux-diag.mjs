import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, permissions: ['microphone'] });
const page = await ctx.newPage();
await page.route('**/api/groq/transcribe', () => new Promise(() => {}));
page.on('console', m => { if (/warn|error/i.test(m.type())) console.log('CONSOLE', m.text().slice(0, 120)); });
await page.goto('http://localhost:4173/clinical-console/full', { waitUntil: 'networkidle', timeout: 60000 });
await page.getByText('Start OPD Recording').first().click();
await page.waitForTimeout(3500);
await page.getByText('Pause Recording').first().click();
await page.waitForFunction(() => document.body.innerText.includes('Whisper Transcribing'), undefined, { timeout: 10000 });
console.log('spinner up at t=0; waiting 55s');
await page.waitForTimeout(55000);
const spinnerStillUp = await page.evaluate(() => document.body.innerText.includes('Whisper Transcribing'));
const statuses = await page.evaluate(() => [...document.querySelectorAll('*')].filter(e => e.children.length === 0 && /note:|timed out|failed|unavailable|error/i.test(e.textContent)).map(e => e.textContent.trim().slice(0, 120)).slice(0, 6));
console.log('spinner-still-up=' + spinnerStillUp);
console.log('status-candidates=' + JSON.stringify(statuses));
await page.screenshot({ path: '/downloads/phase11-timeout-diag.png' });
await b.close();
console.log('done');
